const store=new Map([['unrelated','keep'],['meal-dashboard-cache-v1:owner:week','cache'],['meal-dashboard-cache-v1:owner:week:view','view'],['meal-dashboard-cache-v1:owner:last','week'],['meal-dashboard-cache-v1:other:week','other'],['meal-table-layout-v1:viewer','layout']]);
const storage={get length(){return store.size;},key:index=>[...store.keys()][index],getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value),removeItem:key=>store.delete(key)};
assert.equal(clearDeviceStorage('cache','owner',storage),1);
assert.deepEqual([...store.values()],['keep','view','week','other','layout']);
assert.equal(clearDeviceStorage('layout','owner',storage),1);
assert.throws(()=>clearDeviceStorage('all','owner',storage));
assert.throws(()=>clearDeviceStorage('cache','',storage));
assert.throws(()=>clearDeviceStorage('cache','owner',{get length(){throw Error('denied');}}));

assert.equal(ui.readableTime('14/10/2026 10:35',now).short,'14/10/2026 10:35');
assert.equal(ui.readableTime('2026-02-30T10:35:00+07:00',now),null);assert.equal(ui.readableTime(1e40,now),null);

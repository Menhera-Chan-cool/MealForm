import assert from 'node:assert/strict';
import * as ui from './src/operating-ui.mjs';
import {validateImageFiles} from './src/image-import.mjs';
assert.equal(typeof ui.imageBudget,'function');
assert.deepEqual(ui.imageBudget([{dataUrl:'data:image/png;base64,YQ=='}]),{count:1,bytes:1,remainingBytes:2799999,remainingSlots:4});
assert.equal(ui.imageBudget([{dataUrl:'broken'}]),null);
const full=[{dataUrl:'data:image/png;base64,'+Buffer.alloc(2800000).toString('base64')}];assert.equal(ui.imageBudget(full).remainingBytes,0);assert.throws(()=>validateImageFiles([{type:'image/png',size:1}],full),/vượt/);assert.equal(ui.imageBudget(Array.from({length:5},()=>({dataUrl:'data:image/png;base64,YQ=='}))).remainingSlots,0);
assert.deepEqual(ui.characterBudget('á😀',100),{used:3,remaining:97,warning:false});
assert.deepEqual(ui.characterBudget('a'.repeat(96),100),{used:96,remaining:4,warning:true});
assert.deepEqual(ui.characterBudget('a'.repeat(501),500),{used:501,remaining:-1,warning:true});
assert.deepEqual(ui.characterBudget('a'.repeat(100),100),{used:100,remaining:0,warning:true});
